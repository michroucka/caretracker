-- code is the letter and point of § 6 odst. 1 (meals of c) 1. are split by their two maxima), name the official wording,
-- short_name the colloquial name an imported task gets.
CREATE TABLE statutory_task (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           varchar(10)  NOT NULL UNIQUE,
    name           varchar(255) NOT NULL,
    short_name     varchar(30)  NOT NULL UNIQUE,
    unit_type      "unit_type"  NOT NULL,
    max_unit_price int          NOT NULL CHECK (max_unit_price > 0)
);

