package cz.zcu.kiv.caretracker.config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.util.List;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.Resource;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;
import org.springframework.core.io.support.ResourcePatternResolver;
import org.springframework.jdbc.core.JdbcTemplate;

import cz.zcu.kiv.caretracker.entity.Picture;
import cz.zcu.kiv.caretracker.repository.PictureRepository;
import cz.zcu.kiv.caretracker.service.PictureService;

/**
 * Fills the database with the Czech demo data: people and plans from {@code demo-data/data.sql}
 * (generated by tools/demo-data/generate.py), AI portraits from {@code demo-data/portraits/}, then
 * performed tasks up to now from {@code demo-activity/seed.sql}. Portraits that are missing are skipped.
 */
public class DemoDataSeeder {

    public static final String PORTRAITS_LOCATION = "classpath*:demo-data/portraits/";

    private static final Logger log = LoggerFactory.getLogger(DemoDataSeeder.class);
    // data.sql gives the main organization id 1; client portraits are named by personal numbers within it
    private static final long MAIN_ORGANIZATION_ID = 1L;

    private final JdbcTemplate jdbcTemplate;
    private final PictureService pictureService;
    private final PictureRepository pictureRepository;
    private final String portraitsLocation;
    private final ResourcePatternResolver resources = new PathMatchingResourcePatternResolver();

    public DemoDataSeeder(JdbcTemplate jdbcTemplate, PictureService pictureService, PictureRepository pictureRepository,
                          String portraitsLocation) {
        this.jdbcTemplate = jdbcTemplate;
        this.pictureService = pictureService;
        this.pictureRepository = pictureRepository;
        this.portraitsLocation = portraitsLocation;
    }

    /** Seeds only a database without any organization, so a restart never duplicates the data. */
    public boolean seedIfEmpty() {
        Long organizations = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM organization", Long.class);
        if (organizations != null && organizations > 0) {
            return false;
        }
        seed();
        return true;
    }

    public void seed() {
        runScript("classpath:demo-data/data.sql");
        int portraits = importPortraits();
        log.info("Demo data: people, plans and {} portraits loaded", portraits);
        seedActivity();
    }

    public void seedActivity() {
        try {
            runScript("classpath:demo-activity/seed.sql");
            log.info("Demo activity: performed tasks filled up to now");
        } catch (RuntimeException e) {
            log.error("Demo activity: seeding failed", e);
        }
    }

    // Executed as a single statement on purpose: splitting on ";" would break the DO $$ ... $$ blocks
    private void runScript(String location) {
        try {
            jdbcTemplate.execute(resources.getResource(location).getContentAsString(StandardCharsets.UTF_8));
        } catch (IOException e) {
            throw new IllegalStateException("Cannot read " + location, e);
        }
    }

    private int importPortraits() {
        return importPortraits("clients", "SELECT id FROM client WHERE organization_id = " + MAIN_ORGANIZATION_ID + " AND personal_number = ?",
                "UPDATE client SET picture_id = ? WHERE id = ?")
                + importPortraits("employees", "SELECT id FROM employee WHERE id = CAST(? AS bigint)",
                "UPDATE employee SET picture_id = ? WHERE id = ?");
    }

    private int importPortraits(String folder, String findOwner, String setPicture) {
        int imported = 0;
        for (Resource portrait : findPortraits(folder)) {
            String key = portrait.getFilename().replaceFirst("\\.jpg$", "");
            try {
                List<Long> owner = jdbcTemplate.queryForList(findOwner, Long.class, key);
                if (owner.isEmpty()) {
                    log.warn("Demo data: portrait {}/{} has no owner, skipped", folder, portrait.getFilename());
                    continue;
                }
                Picture picture = pictureRepository.save(pictureService.createPictureFromImage(portrait.getContentAsByteArray()));
                jdbcTemplate.update(setPicture, picture.getId(), owner.getFirst());
                imported++;
            } catch (IOException | RuntimeException e) {
                log.warn("Demo data: portrait {}/{} could not be imported", folder, portrait.getFilename(), e);
            }
        }
        return imported;
    }

    private Resource[] findPortraits(String folder) {
        try {
            return resources.getResources(portraitsLocation + folder + "/*.jpg");
        } catch (IOException e) {
            // no portraits folder at all, e.g. before the images are generated
            return new Resource[0];
        }
    }
}
