CREATE TYPE "accommodation_type" AS ENUM (
    'OWN_FLAT',
    'FAMILY_HOUSE',
    'RENTED_FLAT',
    'SUPPORTED_HOUSING',
    'MUNICIPAL_FLAT',
    'WITH_RELATIVES'
);

CREATE TYPE "access_method" AS ENUM (
    'DOORBELL',
    'KEYS',
    'PHONE_CALL',
    'OTHER'
);

CREATE TABLE municipality (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id       bigint              NOT NULL REFERENCES department (id),
    name                varchar(100)        NOT NULL
);

CREATE UNIQUE INDEX idx_municipality_department_name ON municipality (department_id, lower(name));

CREATE TABLE supported_housing (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id       bigint              NOT NULL REFERENCES department (id),
    name                varchar(100)        NOT NULL,
    street              varchar             NOT NULL,
    city                varchar             NOT NULL,
    postal_code         varchar(6)          NOT NULL,
    active              boolean             NOT NULL DEFAULT true
);

ALTER TABLE client
    ADD COLUMN      accommodation_type      accommodation_type,
    ADD COLUMN      supported_housing_id    bigint          REFERENCES supported_housing (id),
    ADD COLUMN      travel_distance_km      int,
    ADD COLUMN      has_elevator            boolean,
    ADD COLUMN      floor_or_room           varchar(50),
    ADD COLUMN      access_method           access_method,
    ADD COLUMN      lock_code               varchar(20),
    ADD COLUMN      access_note             text;