CREATE TYPE "client_document_type" AS ENUM (
    'CONTRACT',
    'INTAKE_ASSESSMENT',
    'KEY_CONSENT',
    'OTHER'
);

CREATE TABLE client_document (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      bigint                 NOT NULL REFERENCES client (id) ON DELETE CASCADE,
    type           "client_document_type" NOT NULL,
    file_name      varchar(255)           NOT NULL,
    content_type   varchar(50)            NOT NULL,
    size           bigint                 NOT NULL,
    data           bytea                  NOT NULL,
    uploaded_at    timestamp              NOT NULL,
    uploaded_by_id bigint REFERENCES employee (id)
);

CREATE INDEX idx_client_document_client ON client_document (client_id);
